"""Exploration summary of the consolidated data -> docs/data_summary.md.

uv run python scripts/explore.py [--parquet-dir data/parquet] [--out docs/data_summary.md]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from sepsis import io

ROOT = Path(__file__).resolve().parents[1]
GROUPS = {
    "vitals": ["HR", "O2Sat", "Temp", "SBP", "MAP", "DBP", "Resp", "EtCO2"],
    "demographic/admin": ["Age", "Gender", "Unit1", "Unit2", "HospAdmTime", "ICULOS"],
}
HOSPITALS = list(io.HOSPITAL_DIRS)


def md_table(df: pd.DataFrame, floatfmt: str = "{:.1f}") -> str:
    def fmt(v):
        if isinstance(v, int | np.integer):
            return f"{v:,}"
        return floatfmt.format(v) if isinstance(v, float) else str(v)

    head = "| " + " | ".join([df.index.name or ""] + [str(c) for c in df.columns]) + " |"
    sep = "|" + "---|" * (len(df.columns) + 1)
    rows = ["| " + " | ".join([str(i)] + [fmt(v) for v in r]) + " |" for i, r in df.iterrows()]
    return "\n".join([head, sep, *rows])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--parquet-dir", type=Path, default=ROOT / "data" / "parquet")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "data_summary.md")
    args = ap.parse_args()

    dfs = {h: io.read_hospital(args.parquet_dir, h) for h in HOSPITALS}
    variables = [c for c in dfs["A"].columns if c not in ("patient_id", "hospital", "SepsisLabel")]
    label_col = "SepsisLabel"
    out: list[str] = ["# Data summary: PhysioNet/CinC Challenge 2019", ""]
    out.append(
        "Generated by `scripts/explore.py` from the consolidated Parquet files. "
        "Hospital A = `training_setA`, hospital B = `training_setB` (external test set)."
    )
    manifest = args.parquet_dir / "manifest.json"
    if manifest.exists():
        m = json.loads(manifest.read_text())
        out += ["", "## Counts (raw files vs Parquet)", ""]
        rows = {
            h: {
                "patients (raw)": m[h]["raw"]["patients"],
                "patients (parquet)": m[h]["parquet"]["patients"],
                "rows (raw)": m[h]["raw"]["rows"],
                "rows (parquet)": m[h]["parquet"]["rows"],
                "reconciled": "yes" if m[h]["reconciled"] else "NO",
            }
            for h in HOSPITALS
        }
        out.append(
            md_table(
                pd.DataFrame.from_dict(rows, orient="index", dtype=object).rename_axis("hospital")
            )
        )

    # Per-patient summaries
    per_pt = {}
    for h, df in dfs.items():
        g = df.groupby("patient_id", sort=False)
        first = g.head(1).set_index("patient_id")
        per_pt[h] = pd.DataFrame(
            {
                "los": g["ICULOS"].max(),
                "n_rows": g.size(),
                "ever_septic": g[label_col].max().astype(bool),
                "first_label": first[label_col].astype(bool),
                "first_iculos": first["ICULOS"],
            }
        )

    out += ["", "## Label prevalence", ""]
    prev = {}
    for h, df in dfs.items():
        p = per_pt[h]
        prev[h] = {
            "patients": len(p),
            "septic patients": int(p.ever_septic.sum()),
            "patient prevalence %": 100 * p.ever_septic.mean(),
            "patient-hours": len(df),
            "positive hours": int(df[label_col].sum()),
            "hour prevalence %": 100 * df[label_col].mean(),
            "positive hours / septic patient": df[label_col].sum() / max(p.ever_septic.sum(), 1),
        }
    out.append(
        md_table(
            pd.DataFrame.from_dict(prev, orient="index", dtype=object).rename_axis("hospital"),
            "{:,.2f}",
        )
    )
    out += [
        "",
        "`SepsisLabel` is already shifted (1 from 6 h before onset); it is not shifted again.",
    ]

    out += ["", "## Patients positive at their first ICU hour", ""]
    first_pos = {}
    for h in HOSPITALS:
        p = per_pt[h]
        first_pos[h] = {
            "positive at first row": int(p.first_label.sum()),
            "% of all patients": 100 * p.first_label.mean(),
            "% of septic patients": 100 * p.first_label.sum() / max(p.ever_septic.sum(), 1),
        }
    out.append(
        md_table(
            pd.DataFrame.from_dict(first_pos, orient="index", dtype=object).rename_axis("hospital"),
            "{:,.2f}",
        )
    )
    out += [
        "",
        "These patients cannot be warned in advance: the label is already positive when "
        "the first measurement arrives. Report them, and consider reporting lead-time "
        "metrics with and without them.",
    ]

    out += ["", "## Length of stay (hours of ICU data per patient)", ""]
    qs = [0.05, 0.25, 0.5, 0.75, 0.95, 0.99]
    los = {}
    for h in HOSPITALS:
        for name, mask in (
            ("all", slice(None)),
            ("septic", per_pt[h].ever_septic),
            ("non-septic", ~per_pt[h].ever_septic),
        ):
            s = per_pt[h].los[mask] if name != "all" else per_pt[h].los
            los[f"{h} {name}"] = {
                "n": len(s),
                "mean": s.mean(),
                **{f"p{int(q * 100)}": s.quantile(q) for q in qs},
                "max": s.max(),
            }
    out.append(
        md_table(
            pd.DataFrame.from_dict(los, orient="index", dtype=object).rename_axis("group"),
            "{:,.1f}",
        )
    )

    out += ["", "## Missingness (% of patient-hours with no value)", ""]
    miss = pd.DataFrame({h: 100 * dfs[h][variables].isna().mean() for h in HOSPITALS})
    for name, cols in GROUPS.items():
        out += [f"### {name}", "", md_table(miss.loc[cols].rename_axis("variable")), ""]
    labs = [v for v in variables if v not in sum(GROUPS.values(), [])]
    out += ["### labs", "", md_table(miss.loc[labs].rename_axis("variable")), ""]
    out.append(
        "Hospital-level differences in measurement frequency are expected to be a main source "
        "of A-to-B distribution shift; missingness indicators and time-since-measurement "
        "features carry this information."
    )

    # Integrity checks the feature code will rely on
    out += ["", "## Data integrity checks", ""]
    checks = []
    for h, df in dfs.items():
        g = df.groupby("patient_id", sort=False)
        iculos_ok = (g["ICULOS"].apply(lambda s: bool((s.diff().dropna() == 1).all()))).mean()
        monotone = g[label_col].apply(lambda s: bool((s.diff().dropna() >= 0).all())).mean()
        checks.append(
            {
                "hospital": h,
                "% patients with consecutive ICULOS": 100 * iculos_ok,
                "% patients with label never reverting 1->0": 100 * monotone,
                "% patients with ICULOS starting at 1": 100 * (per_pt[h].first_iculos == 1).mean(),
                "duplicate (patient, ICULOS) rows": int(
                    df.duplicated(["patient_id", "ICULOS"]).sum()
                ),
            }
        )
    out.append(md_table(pd.DataFrame(checks).set_index("hospital"), "{:,.2f}"))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
